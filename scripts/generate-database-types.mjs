import { readFile, writeFile } from "node:fs/promises";
import { readdir } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const migrationDir = path.join(root, "supabase", "migrations");
const output = path.join(root, "src", "types", "generated", "database.ts");
const files = (await readdir(migrationDir)).filter((file) => file.endsWith(".sql")).sort();
const sql = (
  await Promise.all(files.map((file) => readFile(path.join(migrationDir, file), "utf8")))
).join("\n");

const enumNames = [...sql.matchAll(/create type public\.(\w+) as enum \(([^;]+)\);/gi)].map(
  ([, name, values]) => ({
    name,
    values: [...values.matchAll(/'([^']+)'/g)].map(([, value]) => value),
  }),
);

function splitDefinitions(body) {
  const result = [];
  let start = 0;
  let depth = 0;
  let quote = false;
  for (let i = 0; i < body.length; i += 1) {
    const char = body[i];
    if (char === "'") quote = !quote;
    if (!quote && char === "(") depth += 1;
    if (!quote && char === ")") depth -= 1;
    if (!quote && depth === 0 && char === ",") {
      result.push(body.slice(start, i).trim());
      start = i + 1;
    }
  }
  result.push(body.slice(start).trim());
  return result;
}

function findTableBody(start) {
  let open = sql.indexOf("(", start);
  let depth = 0;
  let quote = false;
  for (let i = open; i < sql.length; i += 1) {
    const char = sql[i];
    if (char === "'") quote = !quote;
    if (!quote && char === "(") depth += 1;
    if (!quote && char === ")") {
      depth -= 1;
      if (depth === 0) return sql.slice(open + 1, i);
    }
  }
  throw new Error("Unclosed table definition");
}

const tables = [];
for (const match of sql.matchAll(/create table public\.(\w+)\s*\(/gi)) {
  const body = findTableBody(match.index);
  const primaryKeyColumns = new Set([
    ...[...body.matchAll(/primary key\s*\(([^)]+)\)/gi)].flatMap((item) =>
      item[1].split(",").map((name) => name.trim()),
    ),
  ]);
  const columns = [];
  for (const definition of splitDefinitions(body)) {
    const column = definition.match(/^([a-z_]\w*)\s+(.+)$/is);
    if (!column || /^(primary|unique|constraint|check|foreign)\b/i.test(column[1])) continue;
    const [, name, declaration] = column;
    const typeMatch = declaration.match(/^(?:public\.)?([a-z_]\w*)(?:\[\])?/i);
    if (!typeMatch) continue;
    const rawType = typeMatch[1].toLowerCase();
    const nullable =
      !/\bnot null\b/i.test(declaration) &&
      !/\bprimary key\b/i.test(declaration) &&
      !primaryKeyColumns.has(name);
    columns.push({ name, type: rawType, nullable, declaration });
  }
  tables.push({ name: match[1], columns });
}

const scalar = (type) => {
  if (["uuid", "text", "date", "timestamptz", "timestamp", "inet", "bytea"].includes(type))
    return "string";
  if (["integer", "numeric", "bigint", "smallint"].includes(type)) return "number";
  if (type === "boolean") return "boolean";
  if (type === "jsonb" || type === "json") return "Json";
  if (enumNames.some((item) => item.name === type))
    return `Database[\"public\"][\"Enums\"][\"${type}\"]`;
  return "unknown";
};
const property = (column, mode) => {
  const optional =
    mode !== "Row" && (column.nullable || /default|generated always/i.test(column.declaration));
  const type = `${scalar(column.type)}${mode === "Row" && column.nullable ? " | null" : ""}`;
  return `      ${column.name}${optional ? "?" : ""}: ${type}`;
};

let outputText = `/* Generated by scripts/generate-database-types.mjs from supabase/migrations. Do not edit. */\n\n`;
outputText += `export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n`;
outputText += `export type Database = {\n  public: {\n    Tables: {\n`;
for (const table of tables) {
  outputText += `      ${table.name}: {\n        Row: {\n`;
  for (const column of table.columns) outputText += `${property(column, "Row")}\n`;
  outputText += `        };\n        Insert: {\n`;
  for (const column of table.columns) outputText += `${property(column, "Insert")}\n`;
  outputText += `        };\n        Update: {\n`;
  for (const column of table.columns) outputText += `${property(column, "Update")}\n`;
  outputText += `        };\n        Relationships: [];\n      };\n`;
}
outputText += `    };\n    Views: {\n      public_event_schedule: { Row: Record<string, unknown>; Relationships: []; };\n    };\n    Functions: {};\n    Enums: {\n`;
for (const item of enumNames)
  outputText += `      ${item.name}: ${item.values.map((value) => JSON.stringify(value)).join(" | ")};\n`;
outputText += `    };\n    CompositeTypes: {};\n  };\n};\n`;
await writeFile(output, outputText);
console.log(
  `Generated ${tables.length} tables and ${enumNames.length} enums at ${path.relative(root, output)}`,
);
